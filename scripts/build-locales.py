"""Validate complete locale dictionaries and bundle them for instant switching."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
languages = ('en', 'de', 'es', 'tr', 'ru', 'zh-Hans', 'ja', 'pt-BR', 'ko')
locales = {lang: json.loads((root / 'translations' / f'{lang}.json').read_text()) for lang in languages}

def leaves(value, path=''):
    if isinstance(value, dict):
        return {key: text for name, item in value.items() for key, text in leaves(item, f'{path}.{name}'.strip('.')).items()}
    if isinstance(value, list):
        return {key: text for index, item in enumerate(value) for key, text in leaves(item, f'{path}.{index}').items()}
    assert isinstance(value, str) and value.strip(), f'Empty or invalid translation: {path}'
    return {path: value}

reference = leaves(locales['en'])
for language, values in locales.items():
    translated = leaves(values)
    assert translated.keys() == reference.keys(), f'Incomplete language: {language}'
    for key, text in translated.items():
        assert re.findall(r'\{\w+\}', text) == re.findall(r'\{\w+\}', reference[key]), f'Placeholder mismatch: {language} {key}'

output = '// Generated by scripts/build-locales.py from translations/*.json.\nwindow.MineLocales = '
output += json.dumps(locales, ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'locales.js').write_text(output)
print(f'Validated {len(languages)} languages × {len(reference)} text entries. Wrote locales.js.')
